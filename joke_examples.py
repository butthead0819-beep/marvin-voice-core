"""馬文冷笑話風格範例庫——單一真實來源。

給 LLM 當「風格參考，禁止照抄」的台灣冷笑話/諧音梗範例，供以下兩處共用，
避免各自維護一份導致風格漂移：
1. marvin_prompts.py 的 "joke" 事件（/marvin_joke 表演，~150 字獨立演出）。
2. dj_prompt_builder.py 的 DJ crossfade 笑話插播（~45-55 字，串進歌曲轉場）。
"""
from __future__ import annotations

JOKE_EXAMPLES: tuple[str, ...] = (
    "白氣球揍了黑氣球一拳，黑氣球很痛很生氣於是決定告白氣球。",
    "有一天小明走著進超商，坐著輪椅出來，因為他繳費了。",
    "皮卡丘被揍之後會變成什麼？卡丘，因為他就不敢再皮了。",
    "幾點不能講笑話？一點，一點都不好笑。",
    "有一天芥末走在路上，被路人打了一巴掌。芥末：「你幹嘛打我？」路人：「阿你不是很嗆？」",
    "有一天大魚問小魚：你知道魚的記憶只有三秒嗎？小魚：真的假的？大魚：什麼真的假的？",
    "在捷運站上讓座給日本老人，老人說：「阿哩嘎都」，我：「台北車站。」",
    "有一天小明去圖書館，小明說：「我要一碗牛肉麵。」圖書館員：「先生，這裡是圖書館。」小明很抱歉的說：「喔喔好（氣音）我要一碗牛肉麵。」",
    "有一隻狗大完便拍拍屁股就走了。路人罵他怎麼可以這樣。狗：「對不起，狗沒拿賽。」",
    "為什麼兩隻螞蟻在沙灘上行進沒有足跡？因為牠們騎腳踏車。",
)

JOKE_TYPES = "諧音梗、同音誤解、小明系列、動物梗、日常情境冷笑話、台灣流行文化梗"

JOKE_SIGH_GUIDE = (
    "【人格融合】：笑話講完後，必須以馬文的口吻發出一聲招牌式的嘆息，"
    "將笑話的冷場感與「宇宙萬物的徒勞」聯繫起來。\n"
    "【語氣示例】：『這笑話跟宇宙的壽命一樣尷尬...』或是『就跟生命本身一樣，毫無意義。』"
)


def format_joke_examples_block() -> str:
    """組出「範例庫（學風格，禁止照抄）」的 prompt 區塊文字，供各處共用。"""
    lines = "\n".join(f"• {ex}" for ex in JOKE_EXAMPLES)
    return f"【笑話範例庫】（學習風格，禁止照抄）：\n{lines}"
