def build_news_interjection_template(headline: str, song_title: str | None = None) -> str:
    """將乾淨新聞標題格式化為 40-50 字的極簡生活快報接歌模板。"""
    h = (headline or "").strip()
    if not h:
        return get_comedy_fallback()
    # 確保長度不超標
    if len(h) > 26:
        h = h[:25] + "..."
    templates = [
        f"插播一則最新消息：{h}。看來今天話題不少，接著聽這首好歌。",
        f"剛跳出的即時快訊：{h}。吸收完新資訊，換首放鬆的歌聽聽吧。",
        f"帶大家關心一下時事：{h}。看完新聞，接下來這首歌繼續陪大家。",
    ]
    return random.choice(templates)
